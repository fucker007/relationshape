_BY_ID = {b["bid"]: b for b in BOOKS}


def get_book(bid: str):
    return _BY_ID.get(bid)


def list_books(artifacts: list) -> list[dict]:
    """书架视图：题面含正文与法器名，测验答案永不下发。"""
    return [{
        "bid": b["bid"], "title": b["title"], "author": b["author"],
        "artifact": b["artifact"], "text": b["text"],
        "quiz": [{"q": q["q"]} for q in b["quiz"]],
        "owned": b["bid"] in artifacts,
    } for b in BOOKS]


def grade(bid: str, answers: list) -> Optional[list[bool]]:
    """逐题判分（与题库同一口径）。书不存在返回 None。"""
    b = _BY_ID.get(bid)
    if b is None:
        return None
    out = []
    for i, q in enumerate(b["quiz"]):
        ans = answers[i] if i < len(answers) else ""
        out.append(match_answer([q["answer"], *q.get("accept", [])], ans))
    return out
